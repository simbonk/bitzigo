#!/usr/bin/env python3
"""Would You Rather: build the question list and (once) its pixel-art pictures.

  python3 tools/wyr.py                 # rebuild js/wyr-questions.js from tools/wyr-questions.txt
  python3 tools/wyr.py --images        # also draw any missing pictures (needs GEMINI_API_KEY)
  python3 tools/wyr.py --images --only 1,105 --force   # redraw just these questions

One Gemini image per question holds all of its choices in a 2x2 grid. It is
split into one picture per choice, shrunk to a 48px pixel-art sprite with a
small palette and a see-through background, and saved as img/wyr/<id>-<n>.png.
The game never calls Gemini; it only loads these files.
"""
import argparse, base64, io, json, os, re, sys, time, urllib.request
from collections import deque
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'wyr-questions.txt')
OUT_JS = os.path.join(ROOT, 'js', 'wyr-questions.js')
IMG_DIR = os.path.join(ROOT, 'img', 'wyr')
MODEL = os.environ.get('WYR_MODEL', 'gemini-2.5-flash-image')
SIZE = 48      # sprite size in pixels
COLORS = 20    # palette size per sprite

SPOTS = ['top-left', 'top-right', 'bottom-left', 'bottom-right']
STYLE = (
    'A retro video game sprite sheet on a plain white background: four separate sprites floating in a 2x2 layout, '
    'with lots of empty white space between them. There are no panels, boxes, frames, borders or outlines around the sprites. '
    'Style: folksy, hand-made pixel art like an old 16-bit console game: chunky pixels, a small warm palette, '
    'dark outlines on the characters, flat colours, no gradients, no shine, no photo-realism. Each sprite is one simple, '
    'funny, friendly object or character, with no ground or scenery behind it. Any kids are fully dressed in colourful clothes. No text, letters or numbers anywhere.'
)


def load():
    qs = []
    for line in open(SRC, encoding='utf-8'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        qid, q, *choices = line.split('|')
        c = [dict(zip(('t', 'e', 'p'), x.split(';'))) for x in choices]
        qs.append({'id': int(qid), 'q': 'What would you rather ' + q, 'c': c})
    return qs


def write_js(qs):
    # Cards are small, so labels drop a leading "A" or "An".
    short = lambda t: re.sub(r'^(A|An) (.)', lambda m: m.group(2).upper(), t)
    data = [{'id': q['id'], 'q': q['q'], 'c': [[short(c['t']), c['e']] for c in q['c']]} for q in qs]
    body = ',\n'.join('  ' + json.dumps(d, ensure_ascii=False) for d in data)
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/wyr.py from tools/wyr-questions.txt. Edit that file, not this one.\n')
        f.write('// Each choice is [label, emoji]; its picture is img/wyr/<id>-<n>.png (the emoji stands in until it loads).\n')
        f.write('export const QUESTIONS = [\n' + body + ',\n];\n')


def prompt(q):
    parts = [STYLE]
    for i, spot in enumerate(SPOTS):
        parts.append(f'{spot.capitalize()} sprite: ' + (q['c'][i]['p'] + '.' if i < len(q['c']) else 'nothing, leave it empty white.'))
    return ' '.join(parts)


def generate(q, key):
    body = {
        'contents': [{'parts': [{'text': prompt(q)}]}],
        'generationConfig': {'responseModalities': ['IMAGE'], 'imageConfig': {'aspectRatio': '1:1'}},
    }
    url = f'https://generativelanguage.googleapis.com/v1beta/models/{MODEL}:generateContent'
    req = urllib.request.Request(url, json.dumps(body).encode(), {'Content-Type': 'application/json', 'x-goog-api-key': key})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                res = json.load(r)
            for part in res['candidates'][0]['content']['parts']:
                if 'inlineData' in part:
                    return Image.open(io.BytesIO(base64.b64decode(part['inlineData']['data']))).convert('RGB')
            raise RuntimeError('no image in reply')
        except Exception as e:  # rate limits and the odd empty reply: back off and retry
            print(f'  retry {q["id"]}: {e}', file=sys.stderr)
            time.sleep(4 * 2 ** attempt)
    raise RuntimeError(f'gave up on question {q["id"]}')


def whiteness(img, axis, at):
    w, h = img.size
    px = img.load()
    n = h if axis == 'x' else w
    return sum(sum(px[at, i] if axis == 'x' else px[i, at]) > 700 for i in range(0, n, 2))


def split(img):
    """Cut the grid at the whitest column and row near the middle."""
    w, h = img.size
    cx = max(range(int(w * 0.38), int(w * 0.62)), key=lambda x: whiteness(img, 'x', x))
    cy = max(range(int(h * 0.38), int(h * 0.62)), key=lambda y: whiteness(img, 'y', y))
    return [img.crop(b) for b in [(0, 0, cx, cy), (cx, 0, w, cy), (0, cy, cx, h), (cx, cy, w, h)]]


def unframe(tile):
    """Cut away any frame the model drew around a picture: a thin, mostly dark
    band of rows (or columns) with only white between it and the tile's edge."""
    for _ in range(3):
        w, h = tile.size
        px = tile.convert('L').point(lambda v: 1 if v < 200 else 0).load()
        rows = [sum(px[x, y] for x in range(w)) / w for y in range(h)]
        cols = [sum(px[x, y] for y in range(h)) / h for x in range(w)]

        def edge(fr, rev):
            idx = list(range(len(fr)))[::-1] if rev else list(range(len(fr)))
            run = []
            for i in idx[:len(fr) // 3]:
                if fr[i] > 0.6:
                    run.append(i)
                elif run:
                    break
                elif fr[i] > 0.1:
                    return None  # something other than white before any line
            if not run or len(run) > 14:
                return None
            return run[-1]

        top, bottom, left, right = edge(rows, False), edge(rows, True), edge(cols, False), edge(cols, True)
        if top is None and bottom is None and left is None and right is None:
            break
        box = ((left + 1) if left is not None else 0, (top + 1) if top is not None else 0,
               right if right is not None else w, bottom if bottom is not None else h)
        tile = tile.crop(box)
    return tile


def sprite(tile):
    """Trim the white around a picture, square it up and turn it into a small pixel sprite."""
    tile = unframe(tile)
    gray = tile.convert('L').point(lambda v: 255 if v < 235 else 0)
    box = gray.getbbox() or (0, 0, *tile.size)
    art = tile.crop(box)
    side = max(art.size) + 8
    sq = Image.new('RGB', (side, side), (255, 255, 255))
    sq.paste(art, ((side - art.width) // 2, (side - art.height) // 2))
    small = sq.resize((SIZE, SIZE), Image.BOX).quantize(COLORS, method=Image.Quantize.MEDIANCUT).convert('RGBA')
    # Flood the white background in from the edges and make it see-through.
    px = small.load()
    seen, todo = set(), deque((x, y) for x in range(SIZE) for y in (0, SIZE - 1)) + deque((x, y) for y in range(SIZE) for x in (0, SIZE - 1))
    while todo:
        x, y = todo.popleft()
        if (x, y) in seen or not (0 <= x < SIZE and 0 <= y < SIZE):
            continue
        seen.add((x, y))
        r, g, b, _ = px[x, y]
        if min(r, g, b) < 225:
            continue
        px[x, y] = (0, 0, 0, 0)
        todo.extend([(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)])
    return small


def save(img, path):
    q = img.quantize(COLORS + 1, method=Image.Quantize.FASTOCTREE)
    q.save(path, optimize=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--images', action='store_true')
    ap.add_argument('--only', default='')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--raw', default='', help='folder to keep the full-size grids in, for checking')
    ap.add_argument('--resplit', action='store_true', help='re-cut the grids already in --raw instead of drawing new ones')
    a = ap.parse_args()
    qs = load()
    write_js(qs)
    print(f'{len(qs)} questions, {sum(len(q["c"]) for q in qs)} choices -> {os.path.relpath(OUT_JS, ROOT)}')
    if not a.images:
        return
    key = os.environ.get('GEMINI_API_KEY')
    if not key and not a.resplit:
        sys.exit('Set GEMINI_API_KEY first.')
    only = {int(x) for x in a.only.split(',') if x}
    os.makedirs(IMG_DIR, exist_ok=True)
    made = 0
    for q in qs:
        if only and q['id'] not in only:
            continue
        paths = [os.path.join(IMG_DIR, f'{q["id"]:03d}-{i}.png') for i in range(len(q['c']))]
        if not a.force and all(os.path.exists(p) for p in paths):
            continue
        if a.resplit:
            raw = os.path.join(a.raw, f'{q["id"]:03d}.png')
            if not os.path.exists(raw):
                continue
            img = Image.open(raw).convert('RGB')
        else:
            img = generate(q, key)
            made += 1
        if a.raw and not a.resplit:
            os.makedirs(a.raw, exist_ok=True)
            img.save(os.path.join(a.raw, f'{q["id"]:03d}.png'))
        for path, tile in zip(paths, split(img)):
            save(sprite(tile), path)
        print(f'  {q["id"]:03d}: {", ".join(c["t"] for c in q["c"])}')
    print(f'drew {made} grids')


if __name__ == '__main__':
    main()
